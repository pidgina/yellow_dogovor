min_date = datetime.date(2025, 9, 1)
max_date = datetime.date(2025, 12, 31)

def generate_fio():
    """Генерирует случайное ФИО."""
    if random.choice([True, False]):
        return f"{random.choice(surnames_male)} {random.choice(names_male)} {random.choice(patronymics_male)}"
    else:
        return f"{random.choice(surnames_female)} {random.choice(names_female)} {random.choice(patronymics_female)}"

def random_date():
    """Генерирует случайные даты начала и конца работ."""
    start = min_date
    end = max_date
    delta = (end - start).days
    d1 = start + datetime.timedelta(days=random.randint(0, delta))
    # Пакетные работы могут длиться дольше, от 1 до 7 дней
    d2 = d1 + datetime.timedelta(days=random.randint(1, 7))
    return d1.strftime('%d.%m.%Y'), d2.strftime('%d.%m.%Y')

def generate_fake_data(filename='contracts.csv', count=100):
    """Генерирует случайные данные и сохраняет в CSV."""
    with open(filename, 'w', encoding='utf-8', newline='') as f:
        writer = csv.DictWriter(f, fieldnames=['zakazchik', 'ispolnitel', 'uslugi', 'date_start', 'date_end', 'stoimost'])
        writer.writeheader()
        for _ in range(count):
            d1, d2 = random_date()
            package = random.choice(service_packages)
            price = random.randint(package['price_range'][0], package['price_range'][1])
            
            # Округляем цену до сотен для красоты (например, 4500 вместо 4532)
            price = (price // 100) * 100
            
            writer.writerow({
                'zakazchik': generate_fio(),
                'ispolnitel': generate_fio(),
                'uslugi': package['name'],
                'date_start': d1,
                'date_end': d2,
                'stoimost': price
            })
    return count

